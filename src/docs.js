/**
 * One central documentation folder for the whole project: ./docs.
 *
 * The frontend and backend generators each write a README into their own folder. As a last step the CLI moves those
 * into ./docs (api.md, frontend.md), writes an index (docs/README.md) and leaves a short pointer README behind, so
 * there is ONE place to look for documentation.
 */
import fs from 'node:fs/promises'
import path from 'node:path'
import { docsSite } from './docs-site.js'

export const DOCS_DIR = 'docs'

/** Links in the index, per documented part. */
const ENTRIES = {
    'api.md': {
        title: 'API',
        text: 'Every endpoint with body, `curl` example, response and errors, plus start, scripts, `.env`, database and login.'
    },
    'frontend.md': {
        title: 'Frontend',
        text: 'Structure, languages, theme, how to call the API and the login pages.'
    }
}

const pointer = (title, file) => `# ${title}

The documentation lives in one place: [../${DOCS_DIR}/${file}](../${DOCS_DIR}/${file}). See also the
[documentation index](../${DOCS_DIR}/README.md).
`

/** The index of ./docs. `parts` is a list of `{ file }` that exist. */
export function docsIndex(parts, { swagger = null } = {}) {
    const rows = parts.map(({ file }) => `| [${ENTRIES[file].title}](${file}) | ${ENTRIES[file].text} |`)
    return `# Documentation

All documentation of this project, generated by DafkeDD_CLI so it matches what was installed.
Keep it up to date when you add a page, a language or an API call.

| Document | Contents |
| --- | --- |
${rows.join('\n')}
${swagger ? `\nTry the API from the browser (Swagger): **${swagger}**\n` : ''}`
}

/**
 * Step that collects the READMEs of the installed parts into ./docs.
 * `parts` is `[{ dir, file, title }]`; parts without a README are skipped.
 */
export function docsStep({ projectDir, parts, swagger = null }) {
    return {
        title: 'Documentatie samenstellen (./docs)',
        run: async () => {
            const done = []
            for (const { dir, file, title } of parts) {
                const source = path.join(projectDir, dir, 'README.md')
                let content
                try {
                    content = await fs.readFile(source, 'utf8')
                } catch {
                    continue
                }
                await fs.mkdir(path.join(projectDir, DOCS_DIR), { recursive: true })
                await fs.writeFile(path.join(projectDir, DOCS_DIR, file), content)
                await fs.writeFile(source, pointer(title, file))
                done.push({ file, id: file.replace(/\.md$/, ''), title, markdown: content })
            }
            if (done.length > 0) {
                await fs.writeFile(path.join(projectDir, DOCS_DIR, 'README.md'), docsIndex(done, { swagger }))
                // The same documentation as a web page: open docs/index.html in a browser
                const pages = [{ id: 'index', title: 'Overview', markdown: docsIndex(done, { swagger }) }, ...done]
                await fs.writeFile(
                    path.join(projectDir, DOCS_DIR, 'index.html'),
                    docsSite(pages, { title: 'Project documentation', swagger })
                )
            }
        }
    }
}
