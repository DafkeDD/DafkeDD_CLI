/**
 * One central documentation folder for the whole project: ./docs.
 *
 * The frontend and backend generators each write a README into their own folder. As a last step the CLI moves those
 * into ./docs (api.md, frontend.md), writes an index (docs/README.md) and leaves a short pointer README behind, so
 * there is ONE place to look for documentation. `npm run docs` (in ./backend, ./frontend or ./docs) serves it on
 * http://localhost:5000 with a tiny Node server that has no dependencies.
 */
import fs from 'node:fs/promises'
import path from 'node:path'
import { docsSite } from './docs-site.js'

export const DOCS_DIR = 'docs'
export const DOCS_PORT = 5000

/** Tiny static server for ./docs (no dependencies). Port: DOCS_PORT, default ${DOCS_PORT}. */
export const SERVER = `// Serves this folder: npm run docs  ->  http://localhost:${DOCS_PORT}
import { createServer } from 'node:http'
import { readFile } from 'node:fs/promises'
import { extname, join, normalize, sep } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('.', import.meta.url))
const port = Number(process.env.DOCS_PORT) || ${DOCS_PORT}
const types = { '.html': 'text/html', '.md': 'text/markdown', '.css': 'text/css', '.js': 'text/javascript', '.json': 'application/json' }

createServer(async (req, res) => {
    const url = new URL(req.url ?? '/', 'http://localhost')
    const target = normalize(join(root, decodeURIComponent(url.pathname === '/' ? '/index.html' : url.pathname)))
    // Never serve anything outside this folder, nor the server itself
    if (!target.startsWith(root + (root.endsWith(sep) ? '' : sep)) || target.endsWith('serve.mjs')) {
        res.writeHead(404).end('Not found')
        return
    }
    try {
        const body = await readFile(target)
        res.writeHead(200, { 'Content-Type': (types[extname(target)] ?? 'application/octet-stream') + '; charset=utf-8' })
        res.end(body)
    } catch {
        res.writeHead(404).end('Not found')
    }
}).listen(port, '127.0.0.1', () => console.log('Documentation: http://localhost:' + port))
`

const DOCS_PACKAGE = {
    name: 'docs',
    private: true,
    type: 'module',
    scripts: { docs: 'node serve.mjs', start: 'node serve.mjs' }
}

/** Adds `"docs": "node ../docs/serve.mjs"` to a package.json, keeping its indentation. */
async function addDocsScript(file) {
    let text
    try {
        text = await fs.readFile(file, 'utf8')
    } catch {
        return
    }
    const indent = text.match(/^([ \t]+)"/m)?.[1] ?? '  '
    const pkg = JSON.parse(text)
    pkg.scripts = { ...pkg.scripts, docs: `node ../${DOCS_DIR}/serve.mjs` }
    await fs.writeFile(file, JSON.stringify(pkg, null, indent) + '\n')
}

/** Links in the index, per documented part. */
const ENTRIES = {
    'api.md': {
        title: 'API',
        text: 'Every endpoint with body, `curl` example, response and errors, plus start, scripts, `.env`, database and login.'
    },
    'frontend.md': {
        title: 'Frontend',
        text: 'Structure, languages, theme, how to call the API and the login pages.'
    }
}

const pointer = (title, file) => `# ${title}

The documentation lives in one place: [../${DOCS_DIR}/${file}](../${DOCS_DIR}/${file}). See also the
[documentation index](../${DOCS_DIR}/README.md).
`

/** The index of ./docs. `parts` is a list of `{ file }` that exist. */
export function docsIndex(parts, { swagger = null } = {}) {
    const rows = parts.map(({ file }) => `| [${ENTRIES[file].title}](${file}) | ${ENTRIES[file].text} |`)
    return `# Documentation

All documentation of this project, generated by DafkeDD_CLI so it matches what was installed.
Keep it up to date when you add a page, a language or an API call.

Read it as a website: \`npm run docs\` (in \`backend\`, \`frontend\` or \`docs\`), then open http://localhost:${DOCS_PORT}.
Or open \`index.html\` in this folder directly.

| Document | Contents |
| --- | --- |
${rows.join('\n')}
${swagger ? `\nTry the API from the browser (Swagger): **${swagger}**\n` : ''}`
}

/**
 * Step that collects the READMEs of the installed parts into ./docs.
 * `parts` is `[{ dir, file, title }]`; parts without a README are skipped.
 */
export function docsStep({ projectDir, parts, swagger = null }) {
    return {
        title: 'Documentatie samenstellen (./docs)',
        run: async () => {
            const done = []
            for (const { dir, file, title } of parts) {
                const source = path.join(projectDir, dir, 'README.md')
                let content
                try {
                    content = await fs.readFile(source, 'utf8')
                } catch {
                    continue
                }
                await fs.mkdir(path.join(projectDir, DOCS_DIR), { recursive: true })
                await fs.writeFile(path.join(projectDir, DOCS_DIR, file), content)
                await fs.writeFile(source, pointer(title, file))
                await addDocsScript(path.join(projectDir, dir, 'package.json'))
                done.push({ file, id: file.replace(/\.md$/, ''), title, markdown: content })
            }
            if (done.length > 0) {
                await fs.writeFile(path.join(projectDir, DOCS_DIR, 'README.md'), docsIndex(done, { swagger }))
                // The same documentation as a web page: open docs/index.html in a browser
                const pages = [{ id: 'index', title: 'Overview', markdown: docsIndex(done, { swagger }) }, ...done]
                await fs.writeFile(
                    path.join(projectDir, DOCS_DIR, 'index.html'),
                    docsSite(pages, { title: 'Project documentation', swagger })
                )
                await fs.writeFile(path.join(projectDir, DOCS_DIR, 'serve.mjs'), SERVER)
                await fs.writeFile(
                    path.join(projectDir, DOCS_DIR, 'package.json'),
                    JSON.stringify(DOCS_PACKAGE, null, 2) + '\n'
                )
            }
        }
    }
}
